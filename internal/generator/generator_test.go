func TestSameFieldTypeRejectsDistinctNamedTypesWithSamePackageName(t *testing.T) {
	leftPkg := types.NewPackage("example.com/left/dup", "dup")
	rightPkg := types.NewPackage("example.com/right/dup", "dup")
	left := types.NewNamed(types.NewTypeName(0, leftPkg, "Value", nil), types.Typ[types.String], nil)
	right := types.NewNamed(types.NewTypeName(0, rightPkg, "Value", nil), types.Typ[types.String], nil)

	if sameFieldType(left, right) {
		t.Fatal("sameFieldType() = true, want false for distinct named types with matching printed names")
	}
}

func TestSameFieldTypeComparesUnions(t *testing.T) {
	anyConstraint := types.NewInterfaceType(nil, nil).Complete()
	leftParam := types.NewTypeParam(types.NewTypeName(0, nil, "T", nil), anyConstraint)
	sameParam := types.NewTypeParam(types.NewTypeName(0, nil, "T", nil), anyConstraint)
	left := types.NewUnion([]*types.Term{
		types.NewTerm(true, types.Typ[types.Int]),
		types.NewTerm(false, types.NewSlice(leftParam)),
	})
	same := types.NewUnion([]*types.Term{
		types.NewTerm(true, types.Typ[types.Int]),
		types.NewTerm(false, types.NewSlice(sameParam)),
	})
	different := types.NewUnion([]*types.Term{
		types.NewTerm(true, types.Typ[types.Int]),
		types.NewTerm(false, types.Typ[types.String]),
	})

	if !sameFieldType(left, same) {
		t.Fatal("sameFieldType() = false, want true for matching unions with matching type parameter names")
	}
	if sameFieldType(left, different) {
		t.Fatal("sameFieldType() = true, want false for different union terms")
	}
}

