func writePackage(t *testing.T, files map[string]string) string {
	t.Helper()

	dir := t.TempDir()
	for name, content := range files {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func readFile(t *testing.T, path string) string {
	t.Helper()

	content, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(content)
}

func assertPackageBuilds(t *testing.T, dir string) {
	t.Helper()

	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("skipping generated package build because go command is not available")
	}

	cmd := exec.Command("go", "build", "./...")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOCACHE="+filepath.Join(t.TempDir(), "go-build"))
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("generated package does not compile: %v\n%s", err, out)
	}
}

func diffLines(want, got string) string {
	wantLines := strings.SplitAfter(want, "\n")
	gotLines := strings.SplitAfter(got, "\n")
	var b strings.Builder
	for i := 0; i < len(wantLines) || i < len(gotLines); i++ {
		switch {
		case i >= len(wantLines):
			b.WriteString("+")
			b.WriteString(gotLines[i])
		case i >= len(gotLines):
			b.WriteString("-")
			b.WriteString(wantLines[i])
		case wantLines[i] != gotLines[i]:
			b.WriteString("-")
			b.WriteString(wantLines[i])
			b.WriteString("+")
			b.WriteString(gotLines[i])
		}
	}
	return b.String()
}
